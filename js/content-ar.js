/* Merge into Course as parallel *Ar fields (English fields untouched). */
(function mergeArabic() {
  for (const l of (typeof Course !== 'undefined' ? Course.lessons : [])) {
    const a = ContentAr.lessons[l.id];
    if (!a) continue;
    if (a.title) l.titleAr = a.title;
    if (a.blurb) l.blurbAr = a.blurb;
    (l.steps || []).forEach((s, i) => {
      const sa = a.steps && a.steps[i];
      if (!sa) return;
      if (sa.title) s.titleAr = sa.title;
      if (sa.body) s.bodyAr = sa.body;
      if (sa.coach) s.coachAr = sa.coach;
      if (sa.question) s.questionAr = sa.question;
      if (sa.options) s.optionsAr = sa.options;
      if (sa.explain) s.explainAr = sa.explain;
    });
  }
  for (const p of (typeof Course !== 'undefined' ? Course.puzzles : [])) {
    const a = ContentAr.puzzles[p.id];
    if (!a) continue;
    if (a.theme) p.themeAr = a.theme;
    if (a.prompt) p.promptAr = a.prompt;
    if (a.hint) p.hintAr = a.hint;
    if (a.explain) p.explainAr = a.explain;
  }
})();

